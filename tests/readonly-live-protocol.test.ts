test('live abort ignores late chunks and failed/hanging iterator cleanup is unsafe', async () => {
  for (const cleanup of ['done', 'never', 'reject', 'not-done', 'missing']) {
    const controller = new AbortController();
    const value = response('');
    value.body = { [Symbol.asyncIterator]() { return {
      next: () => new Promise<IteratorResult<Uint8Array>>((resolve) => { setTimeout(() => resolve({ done: false, value: Buffer.from(JSON.stringify(completed())) }), 30); }),
      ...(cleanup === 'missing' ? {} : { return: () => cleanup === 'never' ? new Promise<IteratorResult<Uint8Array>>(() => {})
        : cleanup === 'reject' ? Promise.reject(new Error('untrusted cleanup')) : Promise.resolve({ done: cleanup !== 'not-done', value: undefined } as IteratorResult<Uint8Array>) }),
    }; } };
    const pending = decodeReadonlyLiveResponse(value, controller.signal, { workTimeoutMs: 100, cleanupTimeoutMs: 10 });
    controller.abort();
    await assert.rejects(pending, { code: cleanup === 'done' ? 'READONLY_LIVE_CANCELLED' : 'READONLY_LIVE_LIFECYCLE_UNSAFE' });
  }
});

